#!/bin/sh
# Assumption index: each assumption / regime_limit node -> the nodes that require
# it (from the reverse-dependency view built by build-tree.sh). The assumption
# list is derived from nodes/nodes.tsv, not hard-coded.
set -eu
cd "$(dirname "$0")/.."
{
  echo "# Assumption index (Release 0.1)"
  echo
  echo "Every node that carries each assumption / regime as a prerequisite edge —"
  echo "misuse outside that assumption is visible in the graph. Source:"
  echo "\`indexes/reverse-dependencies.txt\` (generated by \`build/build-tree.sh\`)."
  echo
  awk -F '\t' 'NR>1 && ($2=="assumption" || $2=="regime_limit") { print $1 }' nodes/nodes.tsv |
  while IFS= read -r a; do
    line=$(grep -E "^${a}:" indexes/reverse-dependencies.txt || true)
    deps=${line#*:}
    printf '## `%s`\n%s\n\n' "$a" \
      "$(echo "$deps" | tr ' ' '\n' | grep -v '^$' | sort | sed 's/^/  - /')"
  done
} > indexes/assumption-index.md
echo "wrote indexes/assumption-index.md"
