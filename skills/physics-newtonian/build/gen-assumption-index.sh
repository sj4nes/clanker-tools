#!/bin/sh
# Assumption index: each assumption/regime node -> the nodes that require it
# (straight from the reverse-dependency view built by build-tree.sh).
set -eu
cd "$(dirname "$0")/.."
{
  echo "# Assumption index (Release 0.1)"
  echo
  echo "Every formula that carries each assumption as a prerequisite edge — i.e."
  echo "misuse outside that assumption is visible in the graph. Source:"
  echo "\`indexes/reverse-dependencies.txt\` (generated by \`build/build-tree.sh\`)."
  echo
  for a in newtonian_mechanics nonrelativistic point_particle constant_mass \
           inertial_frame isolated_system conservative_force uniform_gravity \
           small_oscillation; do
    line=$(grep -E "^${a}:" indexes/reverse-dependencies.txt || true)
    deps=${line#*:}
    printf '## `%s`\n%s\n\n' "$a" "$(echo "$deps" | tr ' ' '\n' | grep -v '^$' | sed 's/^/  - /')"
  done
} > indexes/assumption-index.md
echo "wrote indexes/assumption-index.md"
