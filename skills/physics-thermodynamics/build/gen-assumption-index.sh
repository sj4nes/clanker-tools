#!/bin/sh
# Assumption index: each assumption / regime_limit node -> the nodes that require
# it (straight from the reverse-dependency view built by build-tree.sh). The node
# list is derived from the registry, not hard-coded, so it stays correct as
# nodes are added.
set -eu
cd "$(dirname "$0")/.."
{
  echo "# Assumption index (Release 0.1)"
  echo
  echo "Every formula that carries each assumption / regime node as a prerequisite"
  echo "edge -- i.e. misuse outside that assumption is visible in the graph."
  echo "Source: \`indexes/reverse-dependencies.txt\` (generated by \`build/build-tree.sh\`)."
  echo
  awk -F '\t' 'NR>1 && ($2=="assumption" || $2=="regime_limit") { print $1 }' nodes/nodes.tsv |
  while read -r a; do
    line=$(grep -E "^${a}:" indexes/reverse-dependencies.txt || true)
    deps=${line#*:}
    printf '## `%s`\n%s\n\n' "$a" \
      "$(echo "$deps" | tr ' ' '\n' | grep -v '^$' | sed 's/^/  - /')"
  done
} > indexes/assumption-index.md
echo "wrote indexes/assumption-index.md"
